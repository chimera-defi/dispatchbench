"""Gemini 4 Hydrogen / Gemini 3.8 Flash (agy) against haiku-low and terra61-low on the same tasks. Reads results/ only; writes results/report/agy_slice.md.

The agy run stopped on a 429 quota error with uneven repeats, so it is compared on slices every listed config completed (first try, repeat 1)."""
import glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGY = ["hydrogen-low", "hydrogen-medium", "hydrogen-high", "gemini38flash-low"]
REF = ["haiku-low", "terra61-low"]


def load():
    rows = []
    for f in glob.glob(os.path.join(ROOT, "results", "*-function.jsonl")):
        rows += [json.loads(l) for l in open(f)]
    return [r for r in rows if r["config"] in AGY + REF and not r["is_error"]]


def table(rows, probs, title):
    out = [f"### {title}", "", f"{len(probs)} tasks, repeat 1 only for agy rows; reference rows use repeat 1 of the 5.", "",
           "| config | pass | median s | mean in tok | mean out tok |", "|---|---|---|---|---|"]
    for c in AGY + REF:
        rs = [r for r in rows if r["config"] == c and r["repeat"] == 1 and r["problem"] in probs]
        if len(rs) != len(probs): continue
        ws = sorted(r["wall_s"] for r in rs); med = ws[len(ws) // 2] if len(ws) % 2 else (ws[len(ws) // 2 - 1] + ws[len(ws) // 2]) / 2
        tok = lambda k: f"{sum(r[k] or 0 for r in rs) / len(rs):,.0f}"
        out.append(f"| {c} | {sum(r['passed'] for r in rs)}/{len(rs)} | {med:.1f} | {tok('in_tok')} | {tok('out_tok')} |")
    return out + [""]


def main():
    rows = load()
    done = {c: {r["problem"] for r in rows if r["config"] == c and r["repeat"] == 1} for c in AGY}
    allp = sorted(set.intersection(*done.values())); p9 = sorted(set.intersection(*(done[c] for c in AGY if c != "hydrogen-high")))
    p12 = sorted(set.intersection(done["hydrogen-low"], done["gemini38flash-low"]))
    n = {c: sum(1 for r in rows if r["config"] == c and r["cli"] == "agy") for c in AGY}
    out = ["# Gemini 4 Hydrogen via agy (generated by analysis/agy_slice.py)", "",
           "Completed agy calls: " + ", ".join(f"{c} {n[c]}" for c in AGY) + ". The run stopped on a quota error (see results/README.md); repeats are uneven, so these are first-try slices, not the 5-repeat main-ladder number.", ""]
    for probs, title in ((allp, "Slice A: every agy config"), (p9, "Slice B: low, medium, flash"), (p12, "Slice C: low and flash, all of p01-p12")):
        out += table(rows, probs, f"{title} ({probs[0][:3]}-{probs[-1][:3]})")
    p = os.path.join(ROOT, "results", "report", "agy_slice.md"); open(p, "w").write("\n".join(out)); print("\n".join(out))


if __name__ == "__main__": main()
