"""Gemini 4 Hydrogen / Gemini 3.8 Flash (agy) against haiku-low and terra61-low on the same tasks. Reads results/ only; writes results/report/agy_slice.md.

The first agy runs stopped on a 429 quota error with uneven repeats, so the older configs are compared on slices every listed config completed (first try, repeat 1). The Hydrogen and Flash rows have since been filled in; the Neon rows are in the main report table, not here."""
import glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGY = ["hydrogen-low", "hydrogen-medium", "hydrogen-high", "gemini38flash-low", "agy-sonnet46-default", "agy-opus46-default", "agy-gptoss120b-medium"]
REF = ["haiku-low", "terra61-low"]


def load():
    rows = []
    for f in glob.glob(os.path.join(ROOT, "results", "*-function.jsonl")):
        rows += [json.loads(l) for l in open(f)]
    return [r for r in rows if r["config"] in AGY + REF and not r["is_error"]]


def span(probs):
    return ", ".join(p[:3] for p in probs)


def table(rows, probs, title, cfgs):
    out = [f"### {title}", "", f"Tasks: {span(probs)} ({len(probs)}), repeat 1; the reference rows use repeat 1 of their 5.", "",
           "| config | pass | median s | mean in tok | mean out tok |", "|---|---|---|---|---|"]
    for c in cfgs + REF:
        rs = [r for r in rows if r["config"] == c and r["repeat"] == 1 and r["problem"] in probs]
        if len(rs) != len(probs): continue
        ws = sorted(r["wall_s"] for r in rs); med = ws[len(ws) // 2] if len(ws) % 2 else (ws[len(ws) // 2 - 1] + ws[len(ws) // 2]) / 2
        tok = lambda k: f"{sum(r[k] or 0 for r in rs) / len(rs):,.0f}"
        out.append(f"| {c} | {sum(r['passed'] for r in rs)}/{len(rs)} | {med:.1f} | {tok('in_tok')} | {tok('out_tok')} |")
    return out + ["Token counts are each CLI's own report (agy counts its harness prompt in input tokens), so they are not a like-for-like prompt size.", ""]


def stops_and_usage():
    """Each cell that stopped (exact error text, kept in cache/calls) and the tokens each config used before the quota ran out: agy reports tokens, not a quota fraction."""
    calls = [json.load(open(f)) for f in glob.glob(os.path.join(ROOT, "cache", "calls", "*.json"))]
    calls = [d for d in calls if d.get("cli") == "agy"]
    out = ["### Stopped cells (exact error text)", "", "| config | cell | time (UTC) | error |", "|---|---|---|---|"]
    def chain(d):  # a cell's current row and every earlier attempt kept under previous_attempt
        while d:
            yield d; d = d.get("previous_attempt")
    for d in sorted((x for c0 in calls for x in chain(c0) if x.get("is_error")), key=lambda d: d["ts"]):
        short = json.loads(d["error"].split("GY_ERROR: ", 1)[-1].strip().split("\n")[0]).get("short_error", d["error"]) if "GY_ERROR" in d["error"] else d["error"]
        out.append(f"| {d['config']} | {d['problem'][:3]} r{d['repeat']} | {d['ts'][11:19]} | {short} |")
    out += ["", "### Quota used before the stop (tokens agy reported)", "", "| config | completed calls | stopped cells | input tok | output tok | thinking tok | wall min |", "|---|---|---|---|---|---|---|"]
    for c in AGY:
        ok = [d for d in calls if d["config"] == c and not d["is_error"]]
        out.append(f"| {c} | {len(ok)} | {sum(1 for d in calls if d['config'] == c and d['is_error'])} | {sum(d['in_tok'] for d in ok):,} | "
                   f"{sum(d['out_tok'] for d in ok):,} | {sum(d['reasoning_tok'] for d in ok):,} | {sum(d['wall_s'] for d in ok) / 60:.1f} |")
    return out + [""]


def main():
    rows = load()
    done = {c: {r["problem"] for r in rows if r["config"] == c and r["repeat"] == 1} for c in AGY}
    n = {c: sum(1 for r in rows if r["config"] == c and r["cli"] == "agy") for c in AGY}
    out = ["# Gemini 4 Hydrogen and other agy models (generated by analysis/agy_slice.py)", "",
           "Completed agy calls: " + ", ".join(f"{c} {n[c]}" for c in AGY) + ". Some runs stopped on the account quota (see the stopped-cells table), so repeats are uneven; these are first-try slices on tasks every listed config completed, not the 5-repeat main-ladder number.", ""]
    for cfgs, title in ((AGY, "Slice A: all seven agy configs"), (["hydrogen-low", "hydrogen-medium", "gemini38flash-low", "agy-sonnet46-default", "agy-gptoss120b-medium"], "Slice B: five configs"),
                        (["hydrogen-low", "gemini38flash-low"], "Slice C: hydrogen-low and flash")):
        probs = sorted(set.intersection(*(done[c] for c in cfgs)))
        out += table(rows, probs, title, cfgs)
    out += stops_and_usage()
    p = os.path.join(ROOT, "results", "report", "agy_slice.md"); open(p, "w").write("\n".join(out)); print("\n".join(out))


if __name__ == "__main__": main()
