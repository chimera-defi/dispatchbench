"""Read-only site sync and deterministic DispatchBench token/selector adaptation."""
import argparse
import base64
import json
from pathlib import Path
import re
import subprocess

REPO = 'chimera-defi/chimericlabs-llc'
FILES = (
    'tokens/nocturne-base.css', 'tokens/fable-maroon.css', 'tokens/fable-data.css',
    'styles.css', 'components/patterns.css', 'dispatchbench/dispatchbench-theme.css',
    'scripts/check-tokens.mjs', 'scripts/check-contrast.mjs', 'readme.md', 'SKILL.md',
    'guidelines/nocturne-guide.md', 'guidelines/site-guide.md', 'theme.json',
)
DS = Path(__file__).resolve().parents[1]
PAGE = DS.parent
BEGIN = '/* FABLE PAGE RULES BEGIN — generated by sync-design-system. */'
END = '/* FABLE PAGE RULES END */'

# Real report hooks; chart families already use the unchanged --data-* variables.
THEME_SELECTORS = {
    'body': 'body', 'main,.page': 'main', 'h1': 'h1', 'h2': 'h2', 'h3': 'h3',
    'a': 'a', 'a:hover': 'a:hover', 'nav.toc a': '.toc a',
    'nav.toc a:hover': '.toc a:hover', 'table': 'table', 'th': 'th',
    'td,th': 'td,th', 'tbody tr+tr td': 'tbody tr+tr td',
    '.pick,.verdict-pick': '.picks li', '.verdict-avoid': '.pill.bad',
    'details>summary': 'details>summary', '.callout,.winner': '.verdict',
    '.chart': '.chart,.ex-chart', '.chart text': '.chart svg text',
    '.chart .grid': '.ex-grid', '.frontier': '.ex-front,path[data-front]',
    '.frontier-ring': '.ex-ring', '.beaten': '.ex-shade,.zone',
    '.cell-all': '.grid .pass', '.cell-most': '.grid .part', '.cell-half': '.grid .fail',
}
PATTERN_SELECTORS = {
    '.ds-kicker': '.ex-kicker', '.ds-kv': '.ex-values',
    '.ds-kv dt': '.ex-values dt', '.ds-kv dd': '.ex-values dd',
    '.btn[aria-pressed="true"]': '.btn[aria-pressed="true"]',
    '.btn:focus-visible': '.btn:focus-visible', 'select.input': 'select.input',
}


def rules(css):
    """Upstream files use flat rules for the selectors adapted here."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    css = re.sub(r'''@import\s+(?:url\([^)]*\)|"[^"]*"|'[^']*')\s*;''', '', css)
    return re.findall(r'([^{}]+)\{([^{}]*)\}', css)


def header(path, sha):
    return f'/* Source: {REPO} design-system/{path}\n   Pinned SHA: {sha} */\n'


def adapt(css, mapping):
    out = []
    for selector, declarations in rules(css):
        selector = selector.strip()
        if selector not in mapping:
            continue
        # Semantic aliases preserve light contrast. Chart copy keeps the 12px floor.
        for old, new in (
            ('var(--color-accent-300)', 'var(--color-link)'),
            ('var(--color-accent-200)', 'var(--color-link-hover)'),
            ('var(--color-neutral-300)', 'var(--color-muted)'),
            ('var(--color-neutral-400)', 'var(--color-subtle)'),
            ('var(--ds-muted)', 'var(--color-muted)'),
            ('var(--color-accent-400)', 'var(--color-kicker)'),
        ):
            declarations = declarations.replace(old, new)
        if selector == '.chart text':
            declarations = 'fill:var(--muted)'  # retain existing responsive type floors
        elif selector == '.cell-all':
            declarations = 'background:var(--cell-all);color:var(--cell-all-text)'
        elif selector == '.cell-most':
            declarations = 'background:var(--cell-most);color:var(--cell-most-text)'
        elif selector == '.cell-half':
            declarations = 'background:var(--cell-half);color:var(--cell-half-text)'
        elif selector == 'main,.page':
            # Retain the report's vertical and safe-area padding.
            declarations = 'max-width:1200px;margin:0 auto;padding-inline:max(clamp(20px,5vw,72px),env(safe-area-inset-left,0px),env(safe-area-inset-right,0px))'
        out.append(mapping[selector] + '{' + declarations.strip() + '}')
    return '\n'.join(out) + '\n'


def build(sources, sha):
    outputs = {}
    for path, css in sources.items():
        if path == 'components/patterns.css':
            css = adapt(css, PATTERN_SELECTORS)
        elif path == 'dispatchbench/dispatchbench-theme.css':
            css = adapt(css, THEME_SELECTORS)
        if path.endswith('.css'):
            css = header(path, sha) + css
        elif path == 'scripts/check-contrast.mjs':
            css = f'// Source: {REPO} design-system/{path}\n// Pinned SHA: {sha}\n' + css
        outputs[DS / path] = css
    # Only variable definitions enter the single swappable token block. The base
    # file also contains component CSS; unrelated components and its remote font
    # import are not loaded by the report.
    tokens = ['/* FABLE TOKENS BEGIN — generated from the pinned site sources. */']
    for path in FILES[:3]:
        tokens.append(header(path, sha))
        tokens.extend(':root{' + body + '}' for selector, body in rules(sources[path]) if selector.strip() == ':root')
    tokens.append((DS / 'tokens/dispatchbench.css').read_text())
    tokens.append('/* FABLE TOKENS END */\n')
    outputs[PAGE / 'tokens.css'] = '\n'.join(line.rstrip() for line in '\n'.join(tokens).splitlines()) + '\n'
    # P4c_ds: page-rule integration belongs to the page slice. Keep this sync
    # confined to vendored assets, tokens, and the shared topbar.
    topbar = re.findall(r'(?m)^\.ds-topbar[^\n]*\{[^\n]*\}', sources['components/patterns.css'])
    if not topbar:
        raise ValueError('upstream patterns.css has no .ds-topbar rules')
    integration = (PAGE / 'topbar.css').read_text().split('/* Scoped integration:', 1)[1]
    outputs[PAGE / 'topbar.css'] = (header('components/patterns.css', sha)
        + '\n'.join(topbar) + '\n\n/* Scoped integration:' + integration)
    outputs[DS / 'SOURCE.json'] = json.dumps({'repo': REPO, 'sha': sha, 'paths': ['design-system/' + p for p in FILES]}, indent=2) + '\n'
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sha', help='full, immutable site commit SHA')
    parser.add_argument('--source-repo', type=Path, help='read the same Git objects from a local site clone (offline)')
    args = parser.parse_args()
    if not re.fullmatch(r'[0-9a-fA-F]{40}', args.sha):
        parser.error('SHA must be a full 40-character commit hash')
    sha = args.sha.lower()
    sources = {}
    # Fetch and prepare everything before touching a destination. A failed fetch
    # leaves the current vendor files and the runtime bundle unchanged.
    for path in FILES:
        if args.source_repo:
            sources[path] = subprocess.check_output(['git', '-C', str(args.source_repo), 'show', f'{sha}:design-system/{path}']).decode()
        else:
            data = subprocess.check_output(['gh', 'api', f'repos/{REPO}/contents/design-system/{path}?ref={sha}'])
            sources[path] = base64.b64decode(json.loads(data)['content']).decode()
    for path, content in build(sources, sha).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    print(f'synced {len(FILES)} site files from {REPO}@{sha}; rebuilt tokens.css and topbar.css')


if __name__ == '__main__':
    main()
